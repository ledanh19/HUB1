/**
 * Convert URL-safe base64 to Uint8Array
 */
function urlBase64ToUint8Array(base64String: string): Uint8Array {
  // Add padding if needed
  let padding = "";
  const remainder = base64String.length % 4;
  if (remainder === 2) padding = "==";
  else if (remainder === 3) padding = "=";
  
  // Convert URL-safe to standard base64
  const base64 = (base64String + padding)
    .replace(/-/g, "+")
    .replace(/_/g, "/");

  const rawData = atob(base64);
  const outputArray = new Uint8Array(rawData.length);

  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

/**
 * Convert Uint8Array to URL-safe base64
 */
function uint8ArrayToUrlBase64(uint8Array: Uint8Array): string {
  let binary = "";
  for (let i = 0; i < uint8Array.length; i++) {
    binary += String.fromCharCode(uint8Array[i]);
  }
  const base64 = btoa(binary);
  return base64.replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

/**
 * Create VAPID JWT for authorization
 * 
 * VAPID keys from web-push generate-vapid-keys:
 * - Public key: 65 bytes uncompressed EC point (04 || x || y) as URL-safe base64
 * - Private key: 32 bytes raw scalar (d) as URL-safe base64
 * 
 * This implementation correctly imports the keys in JWK format.
 */
async function createVapidJwt(
  audience: string,
  subject: string,
  privateKeyBase64: string,
  publicKeyBase64: string
): Promise<string> {
  // JWT Header
  const header = { alg: "ES256", typ: "JWT" };
  const now = Math.floor(Date.now() / 1000);
  
  // JWT Payload  
  const payload = {
    aud: audience,
    exp: now + 12 * 60 * 60, // 12 hours
    sub: subject,
  };

  // Encode header and payload
  const headerBase64 = uint8ArrayToUrlBase64(
    new TextEncoder().encode(JSON.stringify(header))
  );
  const payloadBase64 = uint8ArrayToUrlBase64(
    new TextEncoder().encode(JSON.stringify(payload))
  );

  const unsignedToken = `${headerBase64}.${payloadBase64}`;

  // Decode keys from URL-safe base64
  const privateKeyBytes = urlBase64ToUint8Array(privateKeyBase64);
  const publicKeyBytes = urlBase64ToUint8Array(publicKeyBase64);
  
  console.log(`[vapid] Private key length: ${privateKeyBytes.length}, Public key length: ${publicKeyBytes.length}`);
  
  // Validate key sizes with detailed error messages
  if (privateKeyBytes.length !== 32) {
    const hint = privateKeyBytes.length === 65 
      ? "ERROR: You likely swapped the keys! Private key should be ~43 chars, Public key ~87 chars."
      : "Generate new keys with: npx web-push generate-vapid-keys";
    throw new Error(
      `Invalid VAPID private key length: ${privateKeyBytes.length} bytes, expected 32 bytes. ` +
      `${hint} Then update Supabase secrets: VAPID_PRIVATE_KEY (short ~43 chars) and VAPID_PUBLIC_KEY (long ~87 chars).`
    );
  }
  
  if (publicKeyBytes.length !== 65) {
    const hint = publicKeyBytes.length === 32 
      ? "ERROR: You likely swapped the keys! Public key should be ~87 chars, Private key ~43 chars."
      : "Generate new keys with: npx web-push generate-vapid-keys";
    throw new Error(
      `Invalid VAPID public key length: ${publicKeyBytes.length} bytes, expected 65 bytes. ` +
      `${hint} Then update Supabase secrets.`
    );
  }
  
  if (publicKeyBytes[0] !== 0x04) {
    throw new Error(`Invalid VAPID public key format: expected 0x04 prefix for uncompressed EC point`);
  }

  // Extract x, y coordinates from public key (skip 0x04 prefix)
  const x = publicKeyBytes.slice(1, 33);  // 32 bytes
  const y = publicKeyBytes.slice(33, 65); // 32 bytes
  const d = privateKeyBytes;               // 32 bytes (private key scalar)

  // Build JWK for ECDSA P-256
  const jwk = {
    kty: "EC",
    crv: "P-256",
    x: uint8ArrayToUrlBase64(x),
    y: uint8ArrayToUrlBase64(y),
    d: uint8ArrayToUrlBase64(d),
  };

  console.log(`[vapid] JWK coords - x length: ${x.length}, y length: ${y.length}, d length: ${d.length}`);
  console.log(`[vapid] JWK base64 - x: ${jwk.x.substring(0, 10)}..., y: ${jwk.y.substring(0, 10)}..., d: ${jwk.d.substring(0, 10)}...`);

  // Import the private key
  const cryptoKey = await crypto.subtle.importKey(
    "jwk",
    jwk,
    { name: "ECDSA", namedCurve: "P-256" },
    false,
    ["sign"]
  );

  console.log("[vapid] Key imported successfully");

  // Sign the token
  const signatureBuffer = await crypto.subtle.sign(
    { name: "ECDSA", hash: "SHA-256" },
    cryptoKey,
    new TextEncoder().encode(unsignedToken)
  );

  // Convert signature from DER to JWS format (fixed 64 bytes for ES256)
  const signature = new Uint8Array(signatureBuffer);
  const signatureBase64 = uint8ArrayToUrlBase64(signature);

  return `${unsignedToken}.${signatureBase64}`;
}

