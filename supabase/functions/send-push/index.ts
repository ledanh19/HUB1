/**
 * Encrypt push payload using aes128gcm per RFC 8291
 * 
 * This implements the "Web Push Message Encryption" standard.
 * Reference: https://datatracker.ietf.org/doc/html/rfc8291
 */
async function encryptPayload(
  payloadString: string,
  p256dh: string,
  auth: string
): Promise<{ encrypted: Uint8Array; salt: Uint8Array; publicKey: Uint8Array }> {
  const payloadBytes = new TextEncoder().encode(payloadString);

  // 1. Generate ephemeral ECDH key pair for this message
  const localKeyPair = await crypto.subtle.generateKey(
    { name: "ECDH", namedCurve: "P-256" },
    true,
    ["deriveBits"]
  );

  // 2. Export local public key (65 bytes uncompressed: 0x04 + X + Y)
  const localPublicKeyBuffer = await crypto.subtle.exportKey("raw", localKeyPair.publicKey);
  const localPublicKey = new Uint8Array(localPublicKeyBuffer);

  // 3. Import subscriber's public key (ua_public from the subscription)
  const subscriberPublicKeyBytes = urlBase64ToUint8Array(p256dh);
  const subscriberPublicKey = await crypto.subtle.importKey(
    "raw",
    subscriberPublicKeyBytes.buffer as ArrayBuffer,
    { name: "ECDH", namedCurve: "P-256" },
    false,
    []
  );

  // 4. Perform ECDH to get shared secret
  const ecdhSecretBits = await crypto.subtle.deriveBits(
    { name: "ECDH", public: subscriberPublicKey },
    localKeyPair.privateKey,
    256
  );
  const ecdhSecret = new Uint8Array(ecdhSecretBits);

  // 5. Generate 16-byte random salt
  const salt = crypto.getRandomValues(new Uint8Array(16));
  
  // 6. Get auth secret from subscription
  const authSecret = urlBase64ToUint8Array(auth);

  // 7. Derive IKM (Input Keying Material) per RFC 8291 Section 3.3
  // info = "WebPush: info" || 0x00 || ua_public || as_public
  const infoPrefix = new TextEncoder().encode("WebPush: info\0");
  const ikmInfo = new Uint8Array([
    ...infoPrefix,
    ...subscriberPublicKeyBytes,
    ...localPublicKey
  ]);
  
  // IKM = HKDF-Extract(salt=auth_secret, IKM=ecdh_secret)
  // then HKDF-Expand to get 32 bytes
  const ikm = await hkdf(authSecret, ecdhSecret, ikmInfo, 32);

  // 8. Derive Content Encryption Key (CEK) and Nonce per RFC 8188
  // cek_info = "Content-Encoding: aes128gcm" || 0x00
  const cekInfo = new TextEncoder().encode("Content-Encoding: aes128gcm\0");
  const cek = await hkdf(salt, ikm, cekInfo, 16);

  // nonce_info = "Content-Encoding: nonce" || 0x00
  const nonceInfo = new TextEncoder().encode("Content-Encoding: nonce\0");
  const nonce = await hkdf(salt, ikm, nonceInfo, 12);

  // 9. Prepare the plaintext with padding delimiter
  // Per RFC 8291: plaintext = data || 0x02 (delimiter) || padding (zeros)
  // We use minimal padding: just the delimiter byte
  const paddedPayload = new Uint8Array(payloadBytes.length + 1);
  paddedPayload.set(payloadBytes, 0);
  paddedPayload[payloadBytes.length] = 0x02; // Record delimiter

  // 10. Encrypt with AES-128-GCM
  const encryptionKey = await crypto.subtle.importKey(
    "raw",
    cek.buffer as ArrayBuffer,
    { name: "AES-GCM" },
    false,
    ["encrypt"]
  );

  const ciphertext = new Uint8Array(
    await crypto.subtle.encrypt(
      { name: "AES-GCM", iv: nonce.buffer as ArrayBuffer, tagLength: 128 },
      encryptionKey,
      paddedPayload
    )
  );

  console.log(`[encrypt] Payload: ${payloadBytes.length}b, Ciphertext: ${ciphertext.length}b, Salt: ${salt.length}b, Key: ${localPublicKey.length}b`);

  return { encrypted: ciphertext, salt, publicKey: localPublicKey };
}

/**
 * HKDF (HMAC-based Key Derivation Function) per RFC 5869
 * Simplified for Web Push: single extract + expand operation
 */
async function hkdf(
  salt: Uint8Array,
  ikm: Uint8Array,
  info: Uint8Array,
  length: number
): Promise<Uint8Array> {
  // Extract: PRK = HMAC-SHA256(salt, IKM)
  const extractKey = await crypto.subtle.importKey(
    "raw",
    salt.buffer as ArrayBuffer,
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"]
  );
  const prk = new Uint8Array(
    await crypto.subtle.sign("HMAC", extractKey, ikm.buffer as ArrayBuffer)
  );

  // Expand: OKM = HMAC-SHA256(PRK, info || 0x01) truncated to length
  const expandKey = await crypto.subtle.importKey(
    "raw",
    prk,
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"]
  );
  
  const expandData = new Uint8Array([...info, 0x01]);
  const okm = new Uint8Array(
    await crypto.subtle.sign("HMAC", expandKey, expandData)
  );

  return okm.slice(0, length);
}

// ============================================
// SEND WEB PUSH WITH RETRY
// ============================================

async function sendWebPush(
  subscription: PushSubscription,
  payload: Record<string, unknown>,
  vapidConfig: { publicKey: string; privateKey: string; subject: string },
  requestId: string,
  retryCount = 0
): Promise<PushSendResult> {
  const endpointUrl = new URL(subscription.endpoint);
  const endpointHost = endpointUrl.host;
  const endpointShort = getEndpointShort(subscription.endpoint);
  const isApplePush = endpointHost.includes('apple.com');
  const ttl = "60"; // 60 seconds for test, 86400 for production
  const timestamp = new Date().toISOString();

  console.log(`[send-push][${requestId}] Sending to: ${endpointShort}, isApple: ${isApplePush}, retry: ${retryCount}`);

  try {
    const audience = `${endpointUrl.protocol}//${endpointUrl.host}`;

    // Create VAPID JWT
    const jwt = await createVapidJwt(
      audience,
      vapidConfig.subject,
      vapidConfig.privateKey,
      vapidConfig.publicKey
    );

    console.log(`[send-push][${requestId}] VAPID JWT created, length: ${jwt.length}`);

    let response: Response;

    // ALL push services (including Apple) require aes128gcm encryption
    // The assumption that Apple uses plain JSON was WRONG
    // Apple's Web Push (via web.push.apple.com) uses the same RFC 8291 standard
    const payloadString = JSON.stringify(payload);
    
    // Check payload size before encryption
    const payloadBytes = new TextEncoder().encode(payloadString);
    if (payloadBytes.length > 4000) { // Leave room for encryption overhead
      console.error(`[send-push][${requestId}] Payload too large: ${payloadBytes.length} bytes`);
      return {
        success: false,
        statusCode: 413,
        error: "PAYLOAD_TOO_LARGE",
        payloadTooLarge: true,
        reason: "PAYLOAD_TOO_LARGE",
      };
    }

    console.log(`[send-push][${requestId}] Encrypting payload (${payloadBytes.length} bytes) for ${isApplePush ? 'Apple' : 'Chrome/Firefox'}`);

    const { encrypted, salt, publicKey } = await encryptPayload(
      payloadString,
      subscription.p256dh,
      subscription.auth
    );

    // Build aes128gcm body per RFC 8188
    // Format: salt (16) + rs (4) + idlen (1) + keyid (65) + ciphertext
    const body = new Uint8Array([
      ...salt,                    // 16 bytes salt
      0, 0, 0x10, 0,              // 4 bytes record size (4096 = 0x1000)
      65,                         // 1 byte key id length
      ...publicKey,               // 65 bytes server public key
      ...encrypted,               // ciphertext
    ]);

    console.log(`[send-push][${requestId}] Encrypted body size: ${body.length} bytes`);

    response = await fetch(subscription.endpoint, {
      method: "POST",
      headers: {
        "Content-Type": "application/octet-stream",
        "Content-Encoding": "aes128gcm",
        "Content-Length": body.length.toString(),
        "Authorization": `vapid t=${jwt}, k=${vapidConfig.publicKey}`,
        "TTL": ttl,
        "Urgency": "high",
      },
      body,
    });

    const statusCode = response.status;
    console.log(`[send-push][${requestId}] Response status: ${statusCode}`);

    // SUCCESS (201 Created)
    if (response.ok || statusCode === 201) {
      console.log(`[send-push][${requestId}] ✓ SENT OK to ${endpointShort}`);
      return { success: true, statusCode, reason: "SENT_OK" };
    }

    const errorBody = await response.text();
    console.error(`[send-push][${requestId}] ✗ FAILED: status=${statusCode}, body=${errorBody?.substring(0, 200)}`);

    // CATEGORIZE ERROR BY STATUS CODE

    // 404/410: Subscription expired/invalid - AUTO-CLEAN
    if (statusCode === 404 || statusCode === 410) {
      console.warn(`[send-push][${requestId}] SUBSCRIPTION_GONE: ${endpointShort}`);
      return {
        success: false,
        statusCode,
        error: "SUBSCRIPTION_EXPIRED",
        errorBody: errorBody?.substring(0, 200),
        needResubscribe: true,
        reason: "SUBSCRIPTION_GONE",
      };
    }

    // 401/403: VAPID authorization issue - DO NOT auto-delete
    if (statusCode === 401 || statusCode === 403) {
      console.error(`[send-push][${requestId}] VAPID_UNAUTHORIZED: ${errorBody}`);
      return {
        success: false,
        statusCode,
        error: "VAPID_UNAUTHORIZED",
        errorBody: errorBody?.substring(0, 200),
        vapidMismatch: true,
        reason: "VAPID_UNAUTHORIZED",
      };
    }

    // 400: Bad request - payload/headers issue
    if (statusCode === 400) {
      console.error(`[send-push][${requestId}] BAD_REQUEST: ${errorBody}`);
      return {
        success: false,
        statusCode,
        error: "BAD_REQUEST",
        errorBody: errorBody?.substring(0, 500),
        badRequest: true,
        reason: "BAD_REQUEST",
      };
    }

    // 413: Payload too large
    if (statusCode === 413) {
      console.error(`[send-push][${requestId}] PAYLOAD_TOO_LARGE`);
      return {
        success: false,
        statusCode,
        error: "PAYLOAD_TOO_LARGE",
        payloadTooLarge: true,
        reason: "PAYLOAD_TOO_LARGE",
      };
    }

    // 429/5xx: Rate limit or server error - RETRY ONCE with backoff
    if ((statusCode === 429 || statusCode >= 500) && retryCount < 1) {
      console.warn(`[send-push][${requestId}] SERVER_ERROR ${statusCode}, retrying in 500ms...`);
      await delay(500);
      return sendWebPush(subscription, payload, vapidConfig, requestId, retryCount + 1);
    }

    if (statusCode === 429 || statusCode >= 500) {
      console.error(`[send-push][${requestId}] SERVER_ERROR after retry: ${statusCode}`);
      return {
        success: false,
        statusCode,
        error: `SERVER_ERROR_${statusCode}`,
        errorBody: errorBody?.substring(0, 200),
        serverError: true,
        reason: `SERVER_ERROR_${statusCode}`,
      };
    }

    // Other error
    return {
      success: false,
      statusCode,
      error: errorBody || `HTTP_${statusCode}`,
      errorBody: errorBody?.substring(0, 200),
      reason: `HTTP_${statusCode}`,
    };

  } catch (error) {
    const errorMsg = error instanceof Error ? error.message : "Unknown error";
    const errorStack = error instanceof Error ? error.stack?.substring(0, 500) : "";
    
    console.error(`[send-push][${requestId}] Push send error:`, error);
    console.error(`[send-push][${requestId}] Stack:`, errorStack);
    
    return {
      success: false,
      error: errorMsg,
      reason: "NETWORK_OR_CRYPTO_ERROR",
      errorBody: errorStack,
    };
  }
}

