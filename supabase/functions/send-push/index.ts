/**
 * Validate VAPID keys at startup
 * - Public key: 65 bytes (uncompressed EC point starting with 0x04)
 * - Private key: 32 bytes (raw EC scalar)
 * 
 * Keys MUST be generated by: npx web-push generate-vapid-keys
 * Format: URL-safe Base64 (no padding, - instead of +, _ instead of /)
 */
function validateAndGetVapidConfig(): { publicKey: string; privateKey: string; subject: string } {
  const publicKey = Deno.env.get("VAPID_PUBLIC_KEY");
  const privateKey = Deno.env.get("VAPID_PRIVATE_KEY");
  const subject = Deno.env.get("VAPID_SUBJECT") || "mailto:admin@roomrise.vn";

  if (!publicKey) {
    throw new Error("[VAPID] VAPID_PUBLIC_KEY not configured. Generate with: npx web-push generate-vapid-keys");
  }
  
  if (!privateKey) {
    throw new Error("[VAPID] VAPID_PRIVATE_KEY not configured. Generate with: npx web-push generate-vapid-keys");
  }

  // Pre-validate key sizes before returning
  // This will catch config errors early
  const publicKeyBytes = urlBase64ToUint8Array(publicKey);
  const privateKeyBytes = urlBase64ToUint8Array(privateKey);
  
  if (privateKeyBytes.length !== 32) {
    const hint = privateKeyBytes.length === 65 
      ? "⚠️ KEYS SWAPPED: Private key has 65 bytes (should be public key). Swap them!"
      : "Generate new keys: npx web-push generate-vapid-keys";
    console.error(`[VAPID] CRITICAL: VAPID_PRIVATE_KEY=${privateKeyBytes.length} bytes (expected 32). ${hint}`);
    console.error(`[VAPID] HINT: Private key should be SHORT (~43 chars), Public key should be LONG (~87 chars)`);
    throw new Error(
      `VAPID_PRIVATE_KEY invalid: ${privateKeyBytes.length} bytes, expected 32. ` +
      `${hint} Update Supabase secrets with correct keys.`
    );
  }
  
  if (publicKeyBytes.length !== 65) {
    const hint = publicKeyBytes.length === 32 
      ? "⚠️ KEYS SWAPPED: Public key has 32 bytes (should be private key). Swap them!"
      : "Generate new keys: npx web-push generate-vapid-keys";
    console.error(`[VAPID] CRITICAL: VAPID_PUBLIC_KEY=${publicKeyBytes.length} bytes (expected 65). ${hint}`);
    throw new Error(
      `VAPID_PUBLIC_KEY invalid: ${publicKeyBytes.length} bytes, expected 65. ` +
      `${hint} Update Supabase secrets with correct keys.`
    );
  }
  
  if (publicKeyBytes[0] !== 0x04) {
    console.error(`[VAPID] CRITICAL: VAPID_PUBLIC_KEY invalid prefix: 0x${publicKeyBytes[0].toString(16)}, expected 0x04`);
    throw new Error(`VAPID_PUBLIC_KEY invalid format: must start with 0x04 (uncompressed EC point)`);
  }

  console.log(`[VAPID] Keys validated - public: ${publicKeyBytes.length} bytes, private: ${privateKeyBytes.length} bytes`);
  
  return { publicKey, privateKey, subject };
}

