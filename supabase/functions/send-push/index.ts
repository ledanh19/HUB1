serve(async (req: Request) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  if (req.method !== "POST") {
    return new Response(JSON.stringify({ error: "Method not allowed" }), {
      status: 405,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }

  const requestId = generateRequestId();
  const failures: FailureDetail[] = [];

  try {
    const body: SendPushRequest = await req.json();
    const {
      event_type,
      idempotency_key,
      recipient_user_ids,
      assigned_to_user_id,
      use_triage_group,
      broadcast_all,
      payload,
      source_table,
      source_record_id,
      debug,
    } = body;

    // Validate required fields
    if (!event_type || !idempotency_key || !payload?.title) {
      return new Response(
        JSON.stringify({
          success: false,
          error: "Missing required fields: event_type, idempotency_key, payload.title",
          requestId,
        }),
        {
          status: 400,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    console.log(`[send-push][${requestId}] Processing ${event_type} with key: ${idempotency_key}`);

    // Get and validate VAPID config
    let vapidConfig;
    try {
      vapidConfig = validateAndGetVapidConfig();
      console.log(`[send-push][${requestId}] VAPID validated: fingerprint=...${getVapidFingerprint(vapidConfig.publicKey)}, subject=${vapidConfig.subject}`);
    } catch (error) {
      const errorMsg = error instanceof Error ? error.message : "Unknown error";
      console.error(`[send-push][${requestId}] VAPID validation failed:`, errorMsg);
      return new Response(
        JSON.stringify({
          success: false,
          error: "Push notifications not configured (VAPID keys invalid or missing)",
          details: errorMsg,
          hint: "Generate new keys with: npx web-push generate-vapid-keys",
          requestId,
        }),
        {
          status: 503,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    // Create service client
    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const supabaseServiceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const serviceClient = createClient(supabaseUrl, supabaseServiceKey);

    // Determine recipients
    let targetUserIds: string[] = [];
    let getAllSubscriptions = false;

    if (broadcast_all) {
      getAllSubscriptions = true;
      console.log(`[send-push][${requestId}] Mode: broadcast_all`);
    } else if (recipient_user_ids && recipient_user_ids.length > 0) {
      targetUserIds = recipient_user_ids;
      console.log(`[send-push][${requestId}] Mode: explicit recipients (${targetUserIds.length} users)`);
    } else if (assigned_to_user_id) {
      targetUserIds = [assigned_to_user_id];
      console.log(`[send-push][${requestId}] Mode: assigned_to_user`);
    } else if (use_triage_group) {
      const triageRole = Deno.env.get("TRIAGE_ROLE") || "cskh";
      const { data: triageUsers, error: triageError } = await serviceClient
        .from("user_roles")
        .select("user_id")
        .eq("role", triageRole);

      if (triageError) {
        console.error(`[send-push][${requestId}] Failed to get triage team:`, triageError);
      } else if (triageUsers && triageUsers.length > 0) {
        targetUserIds = triageUsers.map((u) => u.user_id);
        console.log(`[send-push][${requestId}] Mode: triage_group (${targetUserIds.length} users)`);
      } else {
        getAllSubscriptions = true;
        console.log(`[send-push][${requestId}] Mode: triage fallback to broadcast_all`);
      }
    }

    if (!getAllSubscriptions && targetUserIds.length === 0) {
      console.log(`[send-push][${requestId}] No recipients found`);
      return new Response(
        JSON.stringify({
          success: true,
          sent: 0,
          failed: 0,
          total: 0,
          message: "No recipients found",
          requestId,
          failures: [],
        }),
        {
          status: 200,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    // Get subscriptions
    let subscriptions: PushSubscription[] = [];
    let subError;

    if (getAllSubscriptions) {
      const result = await serviceClient
        .from("push_subscriptions")
        .select("user_id, id:id, endpoint, p256dh, auth")
        .eq("is_active", true)
        .or("consecutive_failures.lt.3,consecutive_failures.is.null");

      subscriptions = (result.data || []).map((s) => ({
        user_id: s.user_id,
        subscription_id: s.id,
        endpoint: s.endpoint,
        p256dh: s.p256dh,
        auth: s.auth,
      }));
      subError = result.error;
    } else {
      const result = await serviceClient.rpc("get_users_push_subscriptions", {
        p_user_ids: targetUserIds,
      });
      subscriptions = result.data || [];
      subError = result.error;
    }

    if (subError) {
      console.error(`[send-push][${requestId}] Failed to get subscriptions:`, subError);
      return new Response(
        JSON.stringify({
          success: false,
          error: "Failed to get subscriptions",
          requestId,
        }),
        {
          status: 500,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    if (subscriptions.length === 0) {
      console.log(`[send-push][${requestId}] No active subscriptions found`);
      return new Response(
        JSON.stringify({
          success: true,
          sent: 0,
          failed: 0,
          total: 0,
          duplicates: 0,
          expired: 0,
          message: "No active push subscriptions",
          requestId,
          failures: [],
        }),
        {
          status: 200,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        }
      );
    }

    console.log(`[send-push][${requestId}] Found ${subscriptions.length} subscriptions`);

    // Results counters
    const results = {
      sent: 0,
      duplicates: 0,
      failed: 0,
      expired: 0,
    };

    // Build minimal push payload
    const pushPayload = {
      title: payload.title,
      body: payload.body,
      icon: payload.icon || "/favicon.png",
      badge: payload.badge || "/favicon.png",
      tag: payload.tag || `${event_type}-${Date.now()}`,
      data: {
        type: event_type,
        ts: Date.now(),
        entity_id: payload.entity_id,
        deep_link: payload.deep_link,
        ...payload.data,
      },
    };

    // Send to each subscription
    for (const sub of subscriptions) {
      const endpointShort = getEndpointShort(sub.endpoint);

      // Check idempotency
      const { data: deliveryResult, error: deliveryError } =
        await serviceClient.rpc("try_record_push_delivery", {
          p_event_type: event_type,
          p_idempotency_key: idempotency_key,
          p_recipient_user_id: sub.user_id,
          p_subscription_id: sub.subscription_id,
          p_source_table: source_table || null,
          p_source_record_id: source_record_id || null,
          p_payload_hash: null,
        });

      if (deliveryError) {
        console.error(`[send-push][${requestId}] Delivery record error:`, deliveryError);
        results.failed++;
        failures.push({
          endpointShort,
          userId: sub.user_id.substring(0, 8),
          statusCode: null,
          reason: "DELIVERY_RECORD_ERROR",
          bodySnippet: deliveryError.message,
          timestamp: new Date().toISOString(),
        });
        continue;
      }

      if (deliveryResult === "DUPLICATE") {
        console.log(`[send-push][${requestId}] Duplicate for user ${sub.user_id.substring(0, 8)}`);
        results.duplicates++;
        continue;
      }

      // Send push
      const pushResult = await sendWebPush(sub, pushPayload, vapidConfig, requestId);

      if (pushResult.success) {
        results.sent++;
        // Mark success
        await serviceClient.rpc("mark_push_subscription_success", {
          p_subscription_id: sub.subscription_id,
        });
        console.log(`[send-push][${requestId}] ✓ Sent to ${sub.user_id.substring(0, 8)} via ${endpointShort}`);

      } else if (pushResult.needResubscribe) {
        // 404/410 - AUTO-CLEAN
        results.expired++;
        
        await serviceClient
          .from("push_subscriptions")
          .update({
            is_active: false,
            last_failure_reason: pushResult.reason || "SUBSCRIPTION_GONE",
            last_failure_at: new Date().toISOString(),
          })
          .eq("id", sub.subscription_id);

        console.warn(`[send-push][${requestId}] AUTO-CLEAN: Deactivated ${endpointShort} (${pushResult.reason})`);

        failures.push({
          endpointShort,
          userId: sub.user_id.substring(0, 8),
          statusCode: pushResult.statusCode || null,
          reason: pushResult.reason || "SUBSCRIPTION_GONE",
          bodySnippet: pushResult.errorBody || null,
          timestamp: new Date().toISOString(),
        });

      } else if (pushResult.vapidMismatch) {
        // 401/403 - VAPID issue, log but don't delete
        results.failed++;

        await serviceClient.rpc("mark_push_subscription_failure", {
          p_subscription_id: sub.subscription_id,
          p_reason: `VAPID_MISMATCH_${pushResult.statusCode}`,
        });

        console.error(`[send-push][${requestId}] VAPID_MISMATCH: ${endpointShort}`);

        failures.push({
          endpointShort,
          userId: sub.user_id.substring(0, 8),
          statusCode: pushResult.statusCode || null,
          reason: "VAPID_UNAUTHORIZED",
          bodySnippet: pushResult.errorBody || null,
          timestamp: new Date().toISOString(),
        });

      } else {
        // Other error
        results.failed++;

        await serviceClient.rpc("mark_push_subscription_failure", {
          p_subscription_id: sub.subscription_id,
          p_reason: pushResult.error || "Unknown error",
        });

        failures.push({
          endpointShort,
          userId: sub.user_id.substring(0, 8),
          statusCode: pushResult.statusCode || null,
          reason: pushResult.reason || pushResult.error || "UNKNOWN_ERROR",
          bodySnippet: pushResult.errorBody || null,
          timestamp: new Date().toISOString(),
        });
      }
    }

    console.log(`[send-push][${requestId}] Results: sent=${results.sent}, failed=${results.failed}, expired=${results.expired}, duplicates=${results.duplicates}`);

    // Build response
    const response: Record<string, unknown> = {
      success: true,
      requestId,
      total: subscriptions.length,
      sent: results.sent,
      failed: results.failed,
      expired: results.expired,
      duplicates: results.duplicates,
      // Return up to 3 failure details for debugging
      failures: failures.slice(0, 3),
    };

    if (results.expired > 0) {
      response.needResubscribe = true;
    }

    if (debug) {
      response.vapidFingerprint = getVapidFingerprint(vapidConfig.publicKey);
      response.vapidSubject = vapidConfig.subject;
    }

    return new Response(JSON.stringify(response), {
      status: 200,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });

  } catch (error) {
    console.error(`[send-push][${requestId}] Error:`, error);
    return new Response(
      JSON.stringify({
        success: false,
        error: "Internal server error",
        details: error instanceof Error ? error.message : "Unknown error",
        stack: error instanceof Error ? error.stack?.substring(0, 500) : null,
        requestId,
        failures,
      }),
      {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      }
    );
  }
});
