function generateRequestId(): string {
  return `push_${Date.now()}_${Math.random().toString(36).substring(2, 9)}`;
}

/**
 * Get safe endpoint short for logging (first 20 + last 6 chars)
 */
function getEndpointShort(endpoint: string): string {
  if (!endpoint || endpoint.length < 30) return endpoint;
  return `${endpoint.substring(0, 20)}...${endpoint.substring(endpoint.length - 6)}`;
}

/**
 * Get VAPID public key fingerprint (last 8 chars) for safe logging
 */
function getVapidFingerprint(publicKey: string): string {
  if (!publicKey || publicKey.length < 8) return "INVALID";
  return publicKey.substring(publicKey.length - 8);
}

/**
 * Delay utility for retry logic
 */
function delay(ms: number): Promise<void> {
  return new Promise(resolve => setTimeout(resolve, ms));
}

